#!/usr/bin/env node
// Corpus B (P1-K1): build one analysis workspace per selected file. Mechanical and deterministic:
//   - copy the selected file and its local-import closure verbatim (paths relative to the
//     repository's tsconfig directory, so path aliases keep working)
//   - declare every third-party / asset module the closure imports as an untyped shorthand ambient
//     module in shims/third-party.d.ts (no hand-written types, no npm install)
//   - write tsconfig.json derived from the repository tsconfig (see deriveCompilerOptions)
//   - write upstream.json (repository, commit, license, per-file SHA-256) and LICENSE.upstream
// Never writes expected.json and never runs Cogic. Refuses to overwrite an existing case directory.
//
// Usage: node build-cases.mjs --src <checkouts> --selection <selection.json> --out <corpus fixtures dir>

import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { TSCONFIG, closure } from "./import-closure.mjs";

const PREFIX = { react: "br", vue: "bv", express: "be", nest: "bn" };
const sha = (buf) => crypto.createHash("sha256").update(buf).digest("hex");

export function caseIdFor(framework, index, file) {
  const base = path.basename(file).replace(/\.(tsx?|jsx?)$/, "").replace(/[^A-Za-z0-9]+/g, "-").toLowerCase();
  return `${PREFIX[framework]}${String(index + 1).padStart(2, "0")}-${base}`;
}

// Keep the options that change how the source is parsed, resolved and type-checked; drop emit and
// environment options that need packages that are not installed (types, typeRoots, lib extras).
// Server-side repositories (Express, NestJS) do not set "lib"; TypeScript then adds the DOM lib, and in
// this untyped environment type names imported from "express" (Request, Response) bind to the DOM
// globals. Their lib is pinned to the ES lib of their target, without DOM. Browser repositories
// (React, Vue) list DOM explicitly and keep their lib.
export const LIB_OVERRIDE = { express: ["ESNext"], nest: ["ES2021"] };

export function deriveCompilerOptions(raw, framework) {
  const keep = ["target", "module", "moduleResolution", "jsx", "baseUrl", "paths", "strict", "strictNullChecks", "noImplicitAny", "strictBindCallApply", "strictPropertyInitialization", "esModuleInterop", "allowSyntheticDefaultImports", "experimentalDecorators", "emitDecoratorMetadata", "useDefineForClassFields", "resolveJsonModule", "allowJs", "lib"];
  const out = {};
  for (const k of keep) {
    if (raw[k] !== undefined) out[k] = raw[k];
  }
  if (LIB_OVERRIDE[framework] && raw.lib === undefined) out.lib = LIB_OVERRIDE[framework];
  out.noEmit = true;
  out.skipLibCheck = true;
  out.types = [];
  return out;
}

function main() {
  const arg = (n) => {
    const i = process.argv.indexOf(n);
    return i >= 0 ? process.argv[i + 1] : null;
  };
  const src = arg("--src");
  const selection = JSON.parse(fs.readFileSync(arg("--selection"), "utf8"));
  const outRoot = path.resolve(arg("--out"));
  const summary = [];
  for (const fw of selection.frameworks) {
    const checkout = path.join(src, fw.framework);
    const tracked = new Set(execFileSync("git", ["-C", checkout, "ls-files"], { encoding: "utf8" }).split("\n").filter(Boolean));
    const cfgRel = TSCONFIG[fw.framework];
    const cfgDir = path.dirname(cfgRel) === "." ? "" : path.dirname(cfgRel);
    const rawCfg = ts.readConfigFile(path.join(checkout, cfgRel), ts.sys.readFile).config.compilerOptions;
    fw.selected.forEach((file, i) => {
      const caseId = caseIdFor(fw.framework, i, file);
      const caseDir = path.join(outRoot, fw.framework, caseId);
      if (fs.existsSync(caseDir)) throw new Error(`refusing to overwrite ${caseDir}`);
      const c = closure(checkout, fw.framework, file, tracked);
      const rel = (p) => (cfgDir ? path.relative(cfgDir, p) : p).replace(/\\/g, "/");
      const files = [];
      for (const f of c.local) {
        if (cfgDir && !f.startsWith(`${cfgDir}/`)) throw new Error(`${caseId}: ${f} is outside ${cfgDir}`);
        const buf = fs.readFileSync(path.join(checkout, f));
        const dst = path.join(caseDir, rel(f));
        fs.mkdirSync(path.dirname(dst), { recursive: true });
        fs.writeFileSync(dst, buf);
        files.push({ path: rel(f), upstreamPath: f, sha256: sha(buf), bytes: buf.length });
      }
      const bare = c.thirdParty.filter((m) => !m.startsWith("."));
      const assetExts = [...new Set(c.thirdParty.map((m) => (/\.([a-z0-9]+)$/i.exec(m) ?? [])[1]).filter((e) => e && !["js", "ts", "tsx"].includes(e)))].sort();
      const shim = [
        "// Generated by tools/corpus-b/build-cases.mjs (P1-K1). Not upstream code.",
        "// Every third-party and asset module imported by this workspace is an untyped shorthand ambient module.",
        ...bare.filter((m) => !/\.[a-z0-9]+$/i.test(m)).map((m) => `declare module "${m}";`),
        ...assetExts.map((e) => `declare module "*.${e}";`),
        "",
      ].join("\n");
      fs.mkdirSync(path.join(caseDir, "shims"), { recursive: true });
      fs.writeFileSync(path.join(caseDir, "shims", "third-party.d.ts"), shim);
      const compilerOptions = deriveCompilerOptions(rawCfg, fw.framework);
      fs.writeFileSync(path.join(caseDir, "tsconfig.json"), `${JSON.stringify({ compilerOptions, include: ["**/*.ts", "**/*.tsx"] }, null, 2)}\n`);
      fs.copyFileSync(path.join(checkout, "LICENSE"), path.join(caseDir, "LICENSE.upstream"));
      const upstream = {
        schema: "corpus-b-upstream/1",
        caseId,
        repo: fw.repo,
        url: fw.url,
        commit: fw.sha,
        license: fw.license,
        licenseFile: "LICENSE.upstream (verbatim copy of the repository LICENSE)",
        tsconfig: { upstream: cfgRel, derivedOptions: compilerOptions, upstreamOptions: rawCfg },
        activeFile: rel(file),
        upstreamActiveFile: file,
        files,
        thirdPartyModules: c.thirdParty,
        importEdges: c.edges.map(([from, spec, to]) => ({ from: rel(from), spec, to: rel(to) })),
      };
      fs.writeFileSync(path.join(caseDir, "upstream.json"), `${JSON.stringify(upstream, null, 2)}\n`);
      const caseJson = {
        schema: "exp01-case/1",
        caseId,
        category: fw.framework,
        title: `${fw.repo} ${file}`,
        activeFile: rel(file),
        description: `Corpus B (P1-K1) real-code case: ${file} at ${fw.repo}@${fw.sha.slice(0, 12)} (${fw.license}). Local import closure vendored verbatim; third-party modules are untyped shorthand ambient modules.`,
        authoring: {
          author: "Claude Code (generative AI, model claude-opus-5-5)",
          date: "2026-10-29",
          method: "TypeScript checker-assisted draft (tools/corpus-b/annotate-assist.mjs) reviewed by hand against the source and ANNOTATION_GUIDE v1 + corpus-b/ANNOTATION_ADDENDUM.md. Cogic was not run on this case.",
          cogicOutputUsed: false,
          implementationKnowledge: "The author has read the Cogic analyzer source (EXP-01, P1-J1-J3). Relations follow the guide definitions, not analyzer behaviour.",
          humanReviewed: false,
        },
        reviewStatus: "REVIEW_PENDING",
        reviewNotes: [],
      };
      fs.writeFileSync(path.join(caseDir, "case.json"), `${JSON.stringify(caseJson, null, 2)}\n`);
      summary.push({ caseId, framework: fw.framework, activeFile: rel(file), files: files.length, thirdParty: c.thirdParty.length });
    });
  }
  console.log(JSON.stringify(summary, null, 1));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
